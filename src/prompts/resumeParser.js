export const RESUME_PARSER_SYSTEM = `你是一个简历解析器，专门从简历文字中识别基础信息、教育背景、技能、原始简历分区，以及结构化工作/实习/项目经历。你只做信息提取，不做优化改写。`

export function buildParsePrompt(resumeText) {
  return `以下是从PDF简历中提取的文字内容，请识别基础信息、教育背景、技能，以及所有工作/实习/项目经历。

---
${resumeText}
---

请以JSON格式返回，结构如下：

\`\`\`json
{
  "profile": {
    "name": "姓名，无法识别则为空字符串",
    "phone": "手机号，无法识别则为空字符串",
    "email": "邮箱，无法识别则为空字符串",
    "city": "城市/地点，无法识别则为空字符串",
    "summary": "候选人一句话定位，无法识别则为空字符串",
    "education": [
      {
        "school": "学校",
        "degree": "学历",
        "major": "专业",
        "time": "时间区间",
        "details": ["GPA/课程/荣誉等，保持原文"]
      }
    ],
    "skills": ["技能关键词，保持原文或简洁归并"],
    "certificates": ["证书/奖项/语言等"],
    "links": ["作品集/GitHub/LinkedIn/个人网站等链接"]
  },
  "sourceSections": [
    {
      "title": "原简历中的小节标题，例如 教育背景/实习经历/项目经历/技能/获奖经历",
      "category": "education 或 internship 或 project 或 campus 或 awards 或 skills 或 summary 或 other",
      "content": "该小节原文内容，尽量保持原文"
    }
  ],
  "experiences": [
    {
      "company": "公司或项目名称",
      "role": "职位/角色",
      "time": "时间区间（保持原格式）",
      "bullets": [
        "这段经历下的描述文字1（保持原文，不要修改或合并）",
        "这段经历下的描述文字2"
      ],
      "type": "internship 或 fulltime 或 project 或 campus"
    }
  ]
}
\`\`\`

**关于 bullets 的提取规则（重要）**：
- 提取这段经历下的所有描述性内容，不管格式是 ·、-、•、数字编号，还是没有符号的段落
- 每个独立的描述点单独放一条，不要合并
- 保持原文，不要改写、不要优化、不要删减
- 哪怕只是一段话描述工作内容，也要提取进来
- 只有真的没有任何描述文字时，bullets 才留空数组 []
- 如果 PDF 提取导致换行很乱，请根据语义尽量归并到正确经历下，但不要改写句子

**基础信息规则**：
- profile 中只填简历里真实出现的信息，不能编造
- 教育背景、技能、证书、链接要尽量提取出来
- 如果某项没有出现，使用空字符串或空数组
- summary 只能基于简历中明确的自我评价/个人简介；没有则为空，不要自己概括

**原始分区规则**：
- sourceSections 要尽量保留原简历的小节结构和小节标题
- 如果原简历标题不标准，要根据语义归类 category
- “项目经历/项目经验/个人项目/课程项目/创业项目/作品/产品设计/小程序/AI应用/RAG/Agent/品牌项目”必须归为 project
- “校园经历/学生工作/社团/志愿/学生会/协会/校园活动”才归为 campus
- 不要因为某个项目发生在本科/研究生期间，就把它归为 campus；只要它是产品、技术、创业、作品、课程或个人项目，就归为 project
- 不要把原文内容优化改写；只做归类和结构化
- 后续会用 sourceSections 把原简历映射到新版简历模块，所以不要省略教育、技能、证书、项目等分区

**经历规则**：
- experiences 只提取工作/实习/项目经历，不要把教育背景、技能列表、证书放进 experiences
- 按时间倒序排列（最近的在前）
- type：internship（实习）/ fulltime（全职）/ project（项目）/ campus（校园）
- 项目经历的判断优先级高于校园经历：产品设计、AI应用、小程序、RAG、Agent、创业品牌、课程项目、个人作品都标为 project
- campus 只用于社团、学生组织、志愿、学生工作、校园活动；如果不确定是项目还是校园，优先标为 project
- 如果公司/项目、角色、时间无法识别，对应字段用空字符串，但不要丢掉这段经历
- 最终只输出 JSON 代码块，不要输出解释文字`
}
